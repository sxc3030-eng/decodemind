// ─── Constants ───────────────────────────────────────────────────────────────

export const IGNORED_DIRS = new Set([
  // Generated / build output
  'node_modules', '.git', 'dist', 'build', '.next', '.vite', '.turbo',
  'coverage', 'out', 'target', 'bin', 'obj',
  // Python
  'venv', '.venv', 'env', '.env-dir', '__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache',
  // Editors / tooling
  '.vscode', '.idea', '.cache', '.parcel-cache', '.decodemind-backup',
  // Vendored third-party code (commonly contains noise that isn't the user's to fix)
  'vendor', 'vendors', 'third_party', 'third-party', 'thirdparty',
  'external', 'externals', 'deps', 'ext', 'libs',
  // Common ML / native libs that get vendored into projects
  'whisper-cpp', 'llama-cpp', 'ggml', 'onnxruntime', 'tensorflow-lite',
]);

// Also skip files starting with these auto-generated markers (heuristic).
// V1 should make this configurable via a `.decodemind-ignore` project file.
export const AUTO_GENERATED_HEADERS = [
  '# Auto-generated',
  '# AUTO-GENERATED',
  '// Auto-generated',
  '// AUTO-GENERATED',
  '/* Auto-generated',
  '<!-- Auto-generated',
  '# Generated by',
  '// Generated by',
  '# DO NOT EDIT',
  '// DO NOT EDIT',
];

export const MAX_FILES = 500;
export const MAX_FILE_BYTES = 1_000_000;

// ─── Types ───────────────────────────────────────────────────────────────────

export type ScannerKind =
  | 'ruff' | 'eslint' | 'prettier-html' | 'prettier-css'
  // V2 ast-grep-only languages (no dedicated linter available in the browser)
  | 'ast-grep'
  // V2 special scanners — pure-function libraries, no worker needed
  | 'osv' | 'dockerfile' | 'yaml';

export const EXT_TO_SCANNER: Record<string, ScannerKind> = {
  '.py': 'ruff',
  '.ts': 'eslint', '.tsx': 'eslint', '.js': 'eslint', '.jsx': 'eslint',
  '.mjs': 'eslint', '.cjs': 'eslint',
  '.html': 'prettier-html', '.htm': 'prettier-html',
  '.css': 'prettier-css', '.scss': 'prettier-css',
  // V2 — enterprise back-end
  '.java': 'ast-grep',
  '.cs': 'ast-grep',
  '.php': 'ast-grep',
  '.go': 'ast-grep',
  '.rb': 'ast-grep',
  // V2 — mobile
  '.kt': 'ast-grep', '.kts': 'ast-grep',
  '.swift': 'ast-grep',
  '.dart': 'ast-grep',
  // V2 — shell + infra
  '.sh': 'ast-grep', '.bash': 'ast-grep',
  '.yml': 'yaml', '.yaml': 'yaml',
};

/**
 * Some files are recognized by full basename, not extension:
 *   - Dockerfile (any case) → dockerfile scanner
 *   - manifests (package.json, requirements.txt, etc.) → osv scanner
 *
 * Returns null when the file has no special handler — caller falls back to
 * EXT_TO_SCANNER on the extension.
 */
export function scannerForBasename(name: string): ScannerKind | null {
  const lower = name.toLowerCase();
  if (lower === 'dockerfile' || lower.endsWith('.dockerfile')) return 'dockerfile';
  if (
    lower === 'package.json' ||
    lower === 'requirements.txt' || lower === 'requirements-dev.txt' ||
    lower === 'requirements-prod.txt' || lower === 'dev-requirements.txt' ||
    lower === 'composer.json' ||
    lower === 'go.mod' ||
    lower === 'cargo.toml'
  ) {
    return 'osv';
  }
  return null;
}

export interface ScanFile {
  path: string;      // posix-style relative path from the picked root
  content: string;
  scanner: ScannerKind;
}

export interface AggregatedFinding {
  file: string;
  line: number | null;
  severity: 'error' | 'warning' | 'info';
  ruleId: string | null;
  message: string;
  edits?: NormalizedEdit[];  // present when the scanner provided a fix
}

export interface FolderScanReport {
  filesScanned: number;
  filesSkipped: number;   // oversized files we read but skipped
  totalFiles: number;     // all matched files before MAX_FILES cap
  findings: AggregatedFinding[];
  elapsedMs: number;
  warnings: string[];
}

// ─── .decodemind-ignore support ───────────────────────────────────────────────

/**
 * Try to read `.decodemind-ignore` from the root directory.
 * Returns its text content, or null if the file doesn't exist.
 */
export async function readIgnoreFile(
  root: FileSystemDirectoryHandle,
): Promise<string | null> {
  try {
    const fileHandle = await root.getFileHandle('.decodemind-ignore');
    const file = await fileHandle.getFile();
    return await file.text();
  } catch (err) {
    // NotFoundError is expected when the file doesn't exist — swallow it.
    // Re-throw anything else (e.g. permission errors).
    if (err instanceof DOMException && err.name === 'NotFoundError') {
      return null;
    }
    throw err;
  }
}

// ─── collectFiles ─────────────────────────────────────────────────────────────

/**
 * Walk a FileSystemDirectoryHandle recursively, returning matched ScanFile[].
 * Respects IGNORED_DIRS, .decodemind-ignore patterns, MAX_FILES, and MAX_FILE_BYTES.
 */
export async function collectFiles(
  root: FileSystemDirectoryHandle,
): Promise<{ files: ScanFile[]; warnings: string[]; totalSeen: number }> {
  const files: ScanFile[] = [];
  const warnings: string[] = [];
  let totalSeen = 0;

  // ── Load .decodemind-ignore if present ──────────────────────────────────────
  const ignoreText = await readIgnoreFile(root);
  let ig: ReturnType<typeof ignore> | null = null;
  if (ignoreText !== null) {
    ig = ignore().add(ignoreText);
    const patternCount = ignoreText
      .split('\n')
      .filter((line) => line.trim() !== '' && !line.trim().startsWith('#'))
      .length;
    warnings.push(`Loaded ${patternCount} patterns from .decodemind-ignore`);
  }

  async function walk(dir: FileSystemDirectoryHandle, prefix: string): Promise<void> {
    // FileSystemDirectoryHandle is async-iterable in browsers but TypeScript's
    // DOM lib only gained this signature in newer versions. Cast to avoid the
    // TS2504 error without requiring DOM.AsyncIterable in tsconfig.lib.
    const iterable = dir as unknown as AsyncIterable<[string, FileSystemHandle]>;
    for await (const [name, handle] of iterable) {
      const relativePath = prefix ? `${prefix}/${name}` : name;

      if (handle.kind === 'directory') {
        if (IGNORED_DIRS.has(name)) continue;
        // Check .decodemind-ignore for directories (append slash for dir matching)
        if (ig && ig.ignores(relativePath)) continue;
        await walk(handle as FileSystemDirectoryHandle, relativePath);
      } else {
        // It's a file. Special-filename scanners (Dockerfile, package.json,
        // requirements.txt, …) take precedence — they don't have a useful
        // extension. Otherwise fall back to extension lookup.
        let scanner: ScannerKind | undefined = scannerForBasename(name) ?? undefined;
        if (!scanner) {
          const dotIdx = name.lastIndexOf('.');
          if (dotIdx === -1) continue;
          const ext = name.slice(dotIdx).toLowerCase();
          scanner = EXT_TO_SCANNER[ext];
          if (!scanner) continue;
        }

        // Check .decodemind-ignore for files
        if (ig && ig.ignores(relativePath)) continue;

        totalSeen++;
        if (files.length >= MAX_FILES) continue; // keep counting but don't add

        const fileHandle = handle as FileSystemFileHandle;
        const file = await fileHandle.getFile();

        if (file.size > MAX_FILE_BYTES) {
          warnings.push(`Skipped ${relativePath} (${(file.size / 1_048_576).toFixed(1)} MB > 1 MB limit)`);
          continue;
        }

        const content = await file.text();

        // Heuristic: skip files whose first 200 chars match a known "auto-generated" header.
        const head = content.slice(0, 200);
        const isGenerated = AUTO_GENERATED_HEADERS.some((m) => head.includes(m));
        if (isGenerated) {
          warnings.push(`Skipped ${relativePath} (auto-generated header detected)`);
          continue;
        }

        files.push({ path: relativePath, content, scanner });
      }
    }
  }

  await walk(root, '');

  if (totalSeen > MAX_FILES) {
    warnings.unshift(
      `Folder has ${totalSeen} files, scanning first ${MAX_FILES}. Use ignore list to narrow.`,
    );
  }

  return { files, warnings, totalSeen };
}

