// Worker URLs must be relative literals — NOT `@/` aliases — for Vite's static
// analyzer to bundle them as separate worker chunks.
function makeRuffWorker() {
  return new Worker(new URL('../workers/ruff.worker.ts', import.meta.url), { type: 'module' });
}
function makeEslintWorker() {
  return new Worker(new URL('../workers/eslint.worker.ts', import.meta.url), { type: 'module' });
}
function makePrettierWorker() {
  return new Worker(new URL('../workers/prettier.worker.ts', import.meta.url), { type: 'module' });
}

/** Send one message to a worker and resolve with the response. */
function ask<TReq, TRes>(worker: Worker, req: TReq): Promise<TRes> {
  return new Promise<TRes>((resolve, reject) => {
    worker.onmessage = (e: MessageEvent<TRes>) => resolve(e.data);
    worker.onerror = (e) => reject(new Error(e.message || 'worker error'));
    worker.onmessageerror = () => reject(new Error('worker messageerror'));
    worker.postMessage(req);
  });
}

/**
 * Map a Ruff rule code to a DecodeMind severity.
 *
 * Ruff doesn't carry a per-finding severity — only a rule code. We derive
 * severity from the code prefix so the report's "Critical / Important / Minor"
 * labels match user intuition. See https://docs.astral.sh/ruff/rules/ for codes.
 */
export function ruffSeverity(code: string | null): AggregatedFinding['severity'] {
  if (!code) return 'warning';
  // Security (bandit-ported S*) — real exposure
  if (code.startsWith('S')) return 'error';
  // Pyflakes F* — undefined names, unused imports, real bugs
  if (code.startsWith('F')) return 'error';
  // Bugbear B*, async ASYNC*, blind-except BLE* — warning-level bugs
  if (code.startsWith('B') || code.startsWith('ASYNC') || code.startsWith('BLE')) return 'warning';
  // Real warnings W*
  if (code.startsWith('W')) return 'warning';
  // Style E*, modernisation UP*, complexity C9*, naming N*, annotations ANN*, isort I*, quote Q* — info
  if (
    code.startsWith('E') ||
    code.startsWith('UP') ||
    code.startsWith('C9') ||
    code.startsWith('N') ||
    code.startsWith('ANN') ||
    code.startsWith('Q') ||
    code.startsWith('I')
  ) {
    return 'info';
  }
  return 'warning';
}

function eslintSeverity(n: number): AggregatedFinding['severity'] {
  if (n === 2) return 'error';
  if (n === 1) return 'warning';
  return 'info';
}

// ─── Worker pool ─────────────────────────────────────────────────────────────

const POOL_SIZE = 2;

/**
 * Run a pool of N workers over a list of jobs.
 * Each worker is created by `makeWorker` and processes one job at a time.
 * Jobs are dispatched as workers become free (available-queue style).
 */
async function runPool<TReq, TRes>(
  makeWorker: () => Worker,
  poolSize: number,
  jobs: Array<{ request: TReq; onResult: (res: TRes) => void }>,
): Promise<void> {
  if (jobs.length === 0) return;

  const actualSize = Math.min(poolSize, jobs.length);
  const workers = Array.from({ length: actualSize }, makeWorker);

  // Track which worker is free: a Promise that resolves when the worker
  // finishes its current task (initially all resolve immediately).
  const workerSlots: Promise<void>[] = workers.map(() => Promise.resolve());

  // A queue index we hand out round-trips; but we actually want "pick the
  // soonest free worker", so we use a Promise.race over the slots.
  let jobIndex = 0;

  // Kick off initial batch: one job per worker
  const inFlight: Array<Promise<void>> = [];

  function dispatchNext(workerIdx: number): Promise<void> {
    if (jobIndex >= jobs.length) return Promise.resolve();
    const job = jobs[jobIndex++];
    const p: Promise<void> = ask<TReq, TRes>(workers[workerIdx], job.request).then(
      (res) => {
        job.onResult(res);
        // Chain: when this slot frees, pick the next job for this worker
        workerSlots[workerIdx] = dispatchNext(workerIdx);
      },
    );
    return p;
  }

  // Seed each worker with its first job
  for (let i = 0; i < actualSize; i++) {
    workerSlots[i] = dispatchNext(i);
    inFlight.push(workerSlots[i]);
  }

  // Wait until all workers have drained
  // Since each slot chains into the next job, we wait for all slots to settle
  await Promise.all(workerSlots);

  // Terminate all workers
  for (const w of workers) w.terminate();
}

/**
 * Run all files through the appropriate workers.
 * Uses a pool of POOL_SIZE workers per scanner kind for parallel processing.
 * onProgress fires after each file completes.
 */
export async function scanAllFiles(
  files: ScanFile[],
  onProgress: (
    done: Record<ScannerKind, number>,
    total: Record<ScannerKind, number>,
  ) => void,
): Promise<FolderScanReport> {
  const start = performance.now();
  const findings: AggregatedFinding[] = [];
  const warnings: string[] = [];

  // Pre-count totals per scanner. New scanner kinds default to 0; only those
  // with matched files actually run.
  const total: Record<ScannerKind, number> = {
    ruff: 0, eslint: 0, 'prettier-html': 0, 'prettier-css': 0,
    'ast-grep': 0, osv: 0, dockerfile: 0, yaml: 0,
  };
  for (const f of files) total[f.scanner]++;

  const done: Record<ScannerKind, number> = {
    ruff: 0, eslint: 0, 'prettier-html': 0, 'prettier-css': 0,
    'ast-grep': 0, osv: 0, dockerfile: 0, yaml: 0,
  };

  let filesScanned = 0;
  let filesSkipped = 0;

  // ── Ruff pool ────────────────────────────────────────────────────────────────
  const ruffFiles = files.filter((f) => f.scanner === 'ruff');
  if (ruffFiles.length > 0) {
    type RuffReq = { type: 'scan'; source: string };
    const jobs = ruffFiles.map((file) => ({
      request: { type: 'scan' as const, source: file.content },
      onResult: (res: RuffResponse) => {
        if (res.type === 'error') {
          warnings.push(`Ruff error on ${file.path}: ${res.message}`);
          filesSkipped++;
        } else {
          for (const d of res.diagnostics) {
            const edits = ruffFixToEdits(d);
            findings.push({
              file: file.path,
              line: d.start_location.row,
              severity: ruffSeverity(d.code),
              ruleId: d.code,
              message: d.message,
              ...(edits.length > 0 ? { edits } : {}),
            });
          }
          filesScanned++;
        }
        done.ruff++;
        onProgress({ ...done }, { ...total });
      },
    }));
    await runPool<RuffReq, RuffResponse>(makeRuffWorker, POOL_SIZE, jobs);
  }

  // ── ESLint pool ──────────────────────────────────────────────────────────────
  const eslintFiles = files.filter((f) => f.scanner === 'eslint');
  if (eslintFiles.length > 0) {
    type EslintReq = { type: 'lint'; source: string; filename: string };
    const jobs = eslintFiles.map((file) => ({
      request: { type: 'lint' as const, source: file.content, filename: file.path },
      onResult: (res: EslintResponse) => {
        if (res.type === 'error') {
          warnings.push(`ESLint error on ${file.path}: ${res.message}`);
          filesSkipped++;
        } else {
          for (const m of res.messages) {
            const edits = eslintFixToEdits(m, file.content);
            findings.push({
              file: file.path,
              line: m.line ?? null,
              severity: eslintSeverity(m.severity),
              ruleId: m.ruleId,
              message: m.message,
              ...(edits.length > 0 ? { edits } : {}),
            });
          }
          filesScanned++;
        }
        done.eslint++;
        onProgress({ ...done }, { ...total });
      },
    }));
    await runPool<EslintReq, EslintResponse>(makeEslintWorker, POOL_SIZE, jobs);
  }

  // ── Prettier pool (html + css share one pool) ─────────────────────────────────
  const prettierFiles = files.filter(
    (f) => f.scanner === 'prettier-html' || f.scanner === 'prettier-css',
  );
  if (prettierFiles.length > 0) {
    type PrettierReq = { type: 'format'; source: string; parser: 'html' | 'css' };
    const jobs = prettierFiles.map((file) => {
      const parser = file.scanner === 'prettier-html' ? 'html' as const : 'css' as const;
      return {
        request: { type: 'format' as const, source: file.content, parser },
        onResult: (res: PrettierResponse) => {
          if (res.type === 'error') {
            warnings.push(`Prettier error on ${file.path}: ${res.message}`);
            filesSkipped++;
          } else {
            if (res.changed) {
              findings.push({
                file: file.path,
                line: null,
                severity: 'warning',
                ruleId: 'prettier/format',
                message: 'File is not formatted according to Prettier rules',
              });
            }
            filesScanned++;
          }
          if (file.scanner === 'prettier-html') done['prettier-html']++;
          else done['prettier-css']++;
          onProgress({ ...done }, { ...total });
        },
      };
    });
    await runPool<PrettierReq, PrettierResponse>(makePrettierWorker, POOL_SIZE, jobs);
  }

  // ── OSV scanner (pure function, runs inline — no worker) ─────────────────────
  // Reads manifest files (package.json, requirements.txt, …) and matches
  // declared deps against the bundled CVE snapshot. Zero network calls.
  const osvFiles = files.filter((f) => f.scanner === 'osv');
  for (const file of osvFiles) {
    try {
      const out = scanManifest(file.path, file.content);
      findings.push(...out);
      filesScanned++;
    } catch (err) {
      warnings.push(`OSV scan error on ${file.path}: ${(err as Error).message}`);
      filesSkipped++;
    }
    done.osv++;
    onProgress({ ...done }, { ...total });
  }

  // ── Dockerfile scanner (pure regex library) ──────────────────────────────────
  const dockerfileFiles = files.filter((f) => f.scanner === 'dockerfile');
  for (const file of dockerfileFiles) {
    try {
      // Split logical lines: collapse `\<newline>` continuations.
      const logical = file.content.replace(/\\\r?\n/g, ' ').split(/\r?\n/);
      for (let i = 0; i < logical.length; i++) {
        const line = logical[i];
        for (const rule of DOCKERFILE_RULES) {
          if (rule.matcher(line, i, logical)) {
            findings.push({
              file: file.path,
              line: i + 1,
              severity: rule.severity,
              ruleId: rule.id,
              message: rule.message,
            });
          }
        }
      }
      filesScanned++;
    } catch (err) {
      warnings.push(`Dockerfile scan error on ${file.path}: ${(err as Error).message}`);
      filesSkipped++;
    }
    done.dockerfile++;
    onProgress({ ...done }, { ...total });
  }

  // ── YAML scanner (K8s + GH Actions, regex library with path filter) ──────────
  const yamlFiles = files.filter((f) => f.scanner === 'yaml');
  for (const file of yamlFiles) {
    try {
      for (const rule of YAML_RULES) {
        // Some YAML rules only fire on specific paths (K8s manifests vs
        // .github/workflows). Skip the rule if its pathMatches says no.
        if (rule.pathMatches && !rule.pathMatches(file.path, file.content)) continue;
        const hits = rule.match(file.content);
        for (const hit of hits) {
          findings.push({
            file: file.path,
            line: hit.line,
            severity: rule.severity,
            ruleId: rule.id,
            message: rule.message,
          });
        }
      }
      filesScanned++;
    } catch (err) {
      warnings.push(`YAML scan error on ${file.path}: ${(err as Error).message}`);
      filesSkipped++;
    }
    done.yaml++;
    onProgress({ ...done }, { ...total });
  }

  // ── ast-grep scanner (V2.1) ──────────────────────────────────────────────────
  // Java/Kotlin/Swift/Dart/C#/PHP/Go/Ruby/Bash files are matched and counted
  // here so users see what gets recognized, but actual rule dispatch lives in
  // the dedicated ast-grep worker — wired in a follow-up commit. The 147
  // V2 ast-grep YAML rules + grammars are already on disk and ready to use.
  const astGrepFiles = files.filter((f) => f.scanner === 'ast-grep');
  for (const _file of astGrepFiles) {
    done['ast-grep']++;
    onProgress({ ...done }, { ...total });
  }
  if (astGrepFiles.length > 0) {
    warnings.push(
      `ast-grep: ${astGrepFiles.length} file(s) recognized but rules not yet dispatched (V2.1 — grammar+rules on disk, worker wire-up pending)`,
    );
  }

  return {
    filesScanned,
    filesSkipped,
    totalFiles: files.length,
    findings,
    elapsedMs: Math.round(performance.now() - start),
    warnings,
  };
}
